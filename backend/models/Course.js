const mongoose = require('mongoose');

const CourseSchema = new mongoose.Schema(
  {
    name: { type: String, required: true },
    sinhalaName: { type: String },
    institutionId: { type: mongoose.Schema.Types.ObjectId, ref: 'Institution', required: true },
    institutionName: { type: String, required: true },
    institutionLogo: { type: String },
    qualificationType: {
      type: String,
      enum: [
        'Certificate',
        'Foundation',
        'Diploma',
        'Higher Diploma',
        'HND',
        'Degree',
        'Top-up Degree',
        'Postgraduate Diploma',
        "Master's",
        'PhD',
        'Professional Qualification',
        'Short Course',
      ],
      required: true,
    },
    studyField: {
      type: String,
      enum: [
        'Information Technology',
        'Medicine & Healthcare',
        'Business & Management',
        'Engineering & Technology',
        'Law & Legal Studies',
        'Accounting & Finance',
        'Design & Multimedia',
        'Science & Biotechnology',
        'Education & Teaching',
        'Hospitality & Tourism',
      ],
      required: true,
    },
    duration: { type: String, required: true },
    studyMode: [{ type: String, enum: ['Full-time', 'Part-time', 'Online', 'Hybrid', 'Physical'] }],
    teachingLanguage: [{ type: String, enum: ['English', 'Sinhala', 'Bilingual'] }],
    overview: { type: String, required: true },
    sinhalaOverview: { type: String },
    fees: {
      totalFeeLKR: { type: Number, required: true },
      totalFeeUSD: { type: Number },
      registrationFeeLKR: { type: Number, default: 0 },
      installmentAvailable: { type: Boolean, default: false },
      installmentDetails: { type: String },
      scholarshipAvailable: { type: Boolean, default: false },
      scholarshipNote: { type: String },
    },
    entryRequirements: {
      olRequirement: {
        english: String,
        mathematics: String,
        science: String,
        minimumPasses: Number,
        details: String,
      },
      alRequirement: {
        stream: String,
        minimumPasses: Number,
        details: String,
      },
      previousQualifications: [String],
      minimumAge: Number,
      workExperienceYears: Number,
      otherNotes: String,
    },
    modules: [
      {
        yearOrSemester: String,
        subjects: [String],
      },
    ],
    skillsGained: [String],
    careerOpportunities: [String],
    qualificationAwarded: String,
    nvqLevel: String,
    district: String,
    awardingBody: String,
    accreditation: [String],
    intakeMonths: [String],
    applicationDeadline: String,
    officialApplyLink: String,
    officialWebsite: String,
    lastVerifiedDate: String,
    isPopular: { type: Boolean, default: false },
    isFeatured: { type: Boolean, default: false },
    coverImage: String,
    rating: { type: Number, default: 4.8 },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Course', CourseSchema);
